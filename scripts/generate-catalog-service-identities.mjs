// Derived identity adapter for the existing catalog_life_map seed contract.
// This is not a second catalogue: slugs come exclusively from taxonomy.ts.
import ts from 'typescript';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
const source = ts.createSourceFile('taxonomy.ts', readFileSync('src/lib/catalog/taxonomy.ts', 'utf8'), ts.ScriptTarget.Latest, true);
const ids = [];
function visit(node) {
  if (ts.isPropertyAssignment(node) && node.name.getText(source) === 'services' && ts.isArrayLiteralExpression(node.initializer)) {
    for (const service of node.initializer.elements) {
      if (!ts.isObjectLiteralExpression(service)) throw new Error('Expected literal service');
      const id = service.properties.find(p => ts.isPropertyAssignment(p) && p.name.getText(source) === 'id');
      if (!id || !ts.isStringLiteral(id.initializer)) throw new Error('Expected literal service ID');
      ids.push(id.initializer.text);
    }
  }
  ts.forEachChild(node, visit);
}
visit(source);
if (!ids.length || new Set(ids).size !== ids.length) throw new Error('Missing or duplicate canonical services');
const entries = ids.sort().map(id => {
  const hash = createHash('md5').update(`service:${id}`).digest('hex');
  const uuid = `${hash.slice(0,8)}-${hash.slice(8,12)}-${hash.slice(12,16)}-${hash.slice(16,20)}-${hash.slice(20)}`;
  return `  '${uuid}': '${id}',`;
});
const output = `// Generated by scripts/generate-catalog-service-identities.mjs; do not edit.\n// Matches md5('service:' || slug)::uuid in the existing LifeOS seed.\nexport const CATALOG_SERVICE_SLUG_BY_LIFE_ID: Readonly<Record<string, string>> = {\n${entries.join('\n')}\n};\n`;
const path = 'src/lib/catalog/serviceLifeIdentities.generated.ts';
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw new Error('Stale service identities: run node scripts/generate-catalog-service-identities.mjs');
} else writeFileSync(path, output);
console.log(`Canonical service identities: ${ids.length}`);
