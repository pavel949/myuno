import React from 'react';
import { cleanup, render, screen } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { afterEach, expect, it, vi } from 'vitest';
import ForOwnersPage from './ForOwners';
const state = vi.hoisted(() => ({ language: 'en' }));
vi.mock('@/contexts/LanguageContext', () => ({ useLanguage: () => state }));
vi.mock('@/components/layout/AppLayout', () => ({ AppLayout: ({ children }: { children: React.ReactNode }) => <main>{children}</main> }));
vi.mock('@/components/seo', () => ({ SEOHead: () => null }));
afterEach(cleanup);
it.each(['en', 'ru', 'th'])('preserves both canonical owner journeys without contradictory marketing rates in %s', language => {
 state.language = language;
 const { container } = render(<MemoryRouter initialEntries={['/for-owners']}><ForOwnersPage /></MemoryRouter>);
 expect(screen.getAllByRole('heading', { level: 1 })).toHaveLength(1);
 const paths = container.querySelector('#paths')!;
 expect(paths).toHaveClass('scroll-mt-[calc(var(--consumer-header-height,0px)+1rem)]');
 const cards = paths.querySelectorAll('article');expect(cards).toHaveLength(2);
 expect(cards[0].querySelector('a')).toHaveAttribute('href','/owner/management-landing');
 expect(cards[1].querySelector('a')).toHaveAttribute('href','/mc/onboarding');
 expect(container.querySelector('a[href="/my-property"]')).not.toBeNull();
 expect(container.textContent).not.toMatch(/70\s*\/\s*30|\$25|\$199|\$399/);
});
