// Helper functions
export const getProductsByCategory = (category: MarketCategory) => 
  marketplaceProducts.filter(p => p.category === category);

export const getPopularProducts = () => 
  marketplaceProducts.filter(p => p.isPopular);

export const getNewProducts = () => 
  marketplaceProducts.filter(p => p.isNew);

export const searchProducts = (query: string, language: 'en' | 'ru') => {
  const q = query.toLowerCase();
  return marketplaceProducts.filter(p => {
    const name = language === 'ru' ? p.nameRu : p.nameEn;
    const desc = language === 'ru' ? p.descriptionRu : p.descriptionEn;
    return name.toLowerCase().includes(q) || 
           (desc && desc.toLowerCase().includes(q)) ||
           p.tags?.some(t => t.toLowerCase().includes(q));
  });
};
